// The game names the crafting-advice panel highlights, sorted into the kinds
// the rest of the page already colours differently: a base item is drawn as the
// table's own base column draws one, a skill as a granted property, a rune as
// the table's rune labels. The panel says the same kinds of thing the table
// does, so it says them in the same colours.
//
// Both lists are derived rather than hand-written, from sources that cannot
// contain an ordinary word by construction:
//
//   * **Base items** are spelled as the trade site's own base-item dropdowns
//     spell them, collected in the same pass that produced the advice.
//   * **Skills and auras** are the names the official Russian localisation
//     quotes in the dataset's property lines — `+3 к умению "Тепло"`, `ауру
//     "Шипы"` — plus the English names the mirrored lines use.
//   * **Russian base names** come from the advice's own gloss convention,
//     «Латы мага (Mage Plate)», which is where each one is introduced.
//
// Base *categories* are deliberately absent. `Оружие`, `Шлемы` and `Weapons`
// are ordinary nouns as well as category names, and a sentence opening with one
// — Doom's «Оружие Святой стужи» — would have its first word marked as an item.
// The categories are in the cell the panel opens from anyway.
//
// Every entry is filtered to one a shipped paragraph actually uses, so the list
// cannot accumulate names nothing renders; the generator re-checks that on each
// build. Russian skill names are matched by stem, because they inflect —
// «Святая стужа» has to be found as «Святой стужи».
//
// The highlighter's other rules — glossed names, Latin runs in Russian prose,
// multi-word English names, stat stems, numbers — live in
// `src/runewords/advice-markup.ts` and need no list.
